#!/usr/bin/env python3
"""Write docs/i18n/coverage.md from the gettext catalogs.

Missing translations are a report, never a build failure. Syntax errors are caught by
``compilemessages`` in CI.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LOCALE = ROOT / "controlplane" / "locale"
OUT = ROOT / "docs" / "i18n" / "coverage.md"

MSGID = re.compile(r'^msgid\s+"(.*)"')
MSGSTR = re.compile(r'^msgstr\s+"(.*)"')


def stats(path: Path) -> tuple[int, int]:
    total = done = 0
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        s = line.strip()
        if m := MSGID.match(s):
            if m.group(1):
                total += 1
        elif (m := MSGSTR.match(s)) and m.group(1):
            done += 1
    return done, total


def main() -> int:
    rows = [("en", 100, 0, "source language, no catalog")]
    for po in sorted(LOCALE.glob("*/LC_MESSAGES/*.po")):
        code = po.parent.parent.name
        done, total = stats(po)
        pct = round(100 * done / total) if total else 0
        rows.append((code, pct, total - done, po.name))

    lines = ["# Translation coverage", "", "Generated by `scripts/i18n/audit.py`.", "",
             "| Locale | Complete | Missing | File |", "|---|---|---|---|"]
    lines += [f"| {c} | {p}% | {m} | `{f}` |" for c, p, m, f in rows]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
